-- Tier 3 Phase 1A local historical match ingestion schema.
-- This file intentionally creates only the Phase 1A foundation tables.

CREATE TABLE IF NOT EXISTS seasons (
    season_id TEXT PRIMARY KEY,
    season_name TEXT NOT NULL,
    start_date DATE,
    end_date DATE,
    is_current BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS team_name_mapping (
    source TEXT NOT NULL,
    source_name TEXT NOT NULL,
    canonical_name TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (source, source_name)
);

CREATE TABLE IF NOT EXISTS historical_matches (
    match_id SERIAL PRIMARY KEY,
    season_id TEXT NOT NULL REFERENCES seasons(season_id),
    match_date DATE NOT NULL,
    kickoff_time TIMESTAMP NULL,
    home_team TEXT NOT NULL,
    away_team TEXT NOT NULL,
    home_goals INTEGER NOT NULL,
    away_goals INTEGER NOT NULL,
    result TEXT NOT NULL,
    source TEXT NOT NULL DEFAULT 'football_data',
    source_file TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (season_id, home_team, away_team),
    CHECK (result IN ('H', 'D', 'A')),
    CHECK (home_team <> away_team),
    CHECK (home_goals >= 0),
    CHECK (away_goals >= 0)
);

CREATE TABLE IF NOT EXISTS historical_understat_xg (
    understat_match_id TEXT PRIMARY KEY,
