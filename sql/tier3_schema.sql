CREATE TABLE IF NOT EXISTS standings_before_match_v3 (
    match_id INTEGER NOT NULL REFERENCES historical_matches(match_id),
    season TEXT NOT NULL,
    match_date DATE NOT NULL,
    team_name TEXT NOT NULL,
    opponent_team TEXT NOT NULL,
    venue TEXT NOT NULL,
    is_home INTEGER NOT NULL,
    games_played_before INTEGER NOT NULL,
    wins_before INTEGER NOT NULL,
    draws_before INTEGER NOT NULL,
    losses_before INTEGER NOT NULL,
    points_before INTEGER NOT NULL,
    goals_for_before INTEGER NOT NULL,
    goals_against_before INTEGER NOT NULL,
    goal_diff_before INTEGER NOT NULL,
    ppg_before FLOAT NULL,
    rank_before INTEGER NOT NULL,
    points_to_1st_before INTEGER NOT NULL,
    points_to_4th_before INTEGER NOT NULL,
    points_to_6th_before INTEGER NOT NULL,
    points_above_18th_before INTEGER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (match_id, team_name),
    CHECK (team_name <> opponent_team),
    CHECK (venue IN ('home', 'away')),
    CHECK (is_home IN (0, 1)),
    CHECK (games_played_before >= 0),
    CHECK (wins_before >= 0),
    CHECK (draws_before >= 0),
    CHECK (losses_before >= 0),
    CHECK (points_before = wins_before * 3 + draws_before),
    CHECK (games_played_before = wins_before + draws_before + losses_before),
    CHECK (goals_for_before >= 0),
    CHECK (goals_against_before >= 0),
    CHECK (goal_diff_before = goals_for_before - goals_against_before),
    CHECK (
        (games_played_before = 0 AND ppg_before IS NULL)
        OR (games_played_before > 0 AND ppg_before >= 0)
    ),
    CHECK (rank_before BETWEEN 1 AND 20)
);

